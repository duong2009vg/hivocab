const INDEX_BY_ID = new Map(BILINGUAL_NEWS_INDEX.map((a) => [a.id, a]));

export async function getBilingualNewsById(id) {
  const meta = INDEX_BY_ID.get(id);
  if (!meta) return null;

  let bodyMap = null;
  if (meta.part === 1) {
    const mod = await import('./bilingualNewsPart1.js');
    bodyMap = mod.BILINGUAL_NEWS_PART_1;
  } else if (meta.part === 2) {
    const mod = await import('./bilingualNewsPart2.js');
    bodyMap = mod.BILINGUAL_NEWS_PART_2;
  } else {
    const mod = await import('./bilingualNewsPart3.js');
    bodyMap = mod.BILINGUAL_NEWS_PART_3;
  }

  const body = bodyMap?.[id];
  if (!body) return null;
  return {
    ...meta,
    contentEn: body.contentEn,
    contentVi: body.contentVi,
  };
}
